const assert = require("node:assert/strict");
const { chromium } = require("playwright-core");

const urls = process.argv.slice(2);
if (!urls.length) throw Error("Provide one or more running consumer URLs.");

(async () => {
  const browser = await chromium.launch({ channel: process.env.YOGURT_BROWSER_CHANNEL || "chrome" });
  try {
    for (const url of urls) {
      const page = await browser.newPage();
      const errors = [];
      page.on("pageerror", error => errors.push(String(error)));
      await page.goto(url);
      const button = name => page.getByRole("button", { name, exact: true });
      await button("Agent action").waitFor();
      const noPolicy = await page.evaluate(() => {
        try { window.yogurtFixtureCreateAgent({}); return false; } catch (error) { return error instanceof TypeError; }
      });
      assert.equal(noPolicy, true, "a host policy is required");
      await page.waitForFunction(() => window.yogurtFixtureAgent?.snapshot().some(item => item.label === "Agent action"));
      const snapshot = await page.evaluate(() => window.yogurtFixtureAgent.snapshot());
      assert.equal(snapshot.find(item => item.label === "Private token")?.value, "[redacted]");
      assert.equal(snapshot.some(item => item.label === "Hidden text"), false);
      assert(snapshot.find(item => item.label === "Agent action")?.actions.includes("press"), "installed button must be visible to the consumer bridge");
      const allowed = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent action", action: "press" }] }));
      assert.equal(allowed.ok, true);
      assert.equal(await page.getByTestId("calls").textContent(), "1");
      assert(snapshot.find(item => item.label === "Agent checkbox")?.actions.includes("setChecked"));
      const checked = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent checkbox", action: "setChecked", args: [true] }] }));
      assert.equal(checked.ok, true);
      assert.equal(await page.getByRole("checkbox", { name: "Agent checkbox" }).getAttribute("aria-checked"), "true");
      assert.equal(await page.getByTestId("checkbox-changes").textContent(), "1");
      const refusedCheckbox = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Denied checkbox", action: "setChecked", args: [false] }] }));
      assert.equal(refusedCheckbox.ok, false);
      assert.equal(await page.getByRole("checkbox", { name: "Denied checkbox" }).getAttribute("aria-checked"), "true");
      assert.equal(await page.getByRole("checkbox", { name: "Mixed checkbox" }).getAttribute("aria-checked"), "mixed");
      assert.equal(await page.getByRole("checkbox", { name: "Disabled checkbox" }).isDisabled(), true);
      assert(snapshot.find(item => item.label === "Agent switch")?.actions.includes("setChecked"));
      const switched = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent switch", action: "setChecked", args: [true] }] }));
      assert.equal(switched.ok, true);
      assert.equal(await page.getByRole("switch", { name: "Agent switch" }).getAttribute("aria-checked"), "true");
      assert.equal(await page.getByTestId("switch-changes").textContent(), "1");
      const refusedSwitch = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Denied switch", action: "setChecked", args: [false] }] }));
      assert.equal(refusedSwitch.ok, false);
      assert.equal(await page.getByRole("switch", { name: "Denied switch" }).getAttribute("aria-checked"), "true");
      assert.equal(await page.getByRole("switch", { name: "Disabled switch" }).isDisabled(), true);
      assert(snapshot.find(item => item.label === "Agent title")?.actions.includes("setValue"));
      const changedTitle = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent title", action: "setValue", args: ["Atlas"] }] }));
      assert.equal(changedTitle.ok, true);
      assert.equal(await page.getByRole("textbox", { name: "Agent title" }).inputValue(), "Atlas");
      assert.equal(await page.getByTestId("title-changes").textContent(), "1");
      const deniedText = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Denied text", action: "setValue", args: ["Altered"] }] }));
      assert.equal(deniedText.ok, false);
      assert.equal(await page.getByRole("textbox", { name: "Denied text" }).inputValue(), "Private");
      assert.equal(await page.getByRole("textbox", { name: "Disabled text" }).isDisabled(), true);
      const changedSearch = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent search", action: "setValue", args: ["Found"] }] }));
      assert.equal(changedSearch.ok, true);
      assert.equal(await page.getByRole("searchbox", { name: "Agent search" }).inputValue(), "Found");
      assert.equal(await page.getByTestId("search-changes").textContent(), "1");
      await button("Clear agent search").click();
      assert.equal(await page.getByRole("searchbox", { name: "Agent search" }).inputValue(), "");
      assert.equal(await page.getByTestId("search-changes").textContent(), "2");
      assert.equal(await page.getByRole("searchbox", { name: "Agent search" }).evaluate(element => document.activeElement === element), true);
      const notes = page.getByRole("textbox", { name: "Agent notes" });
      assert.equal(await notes.getAttribute("rows"), "3");
      assert(snapshot.find(item => item.label === "Agent notes")?.actions.includes("setValue"));
      const changedNotes = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent notes", action: "setValue", args: ["Updated note"] }] }));
      assert.equal(changedNotes.ok, true);
      assert.equal(await notes.inputValue(), "Updated note");
      assert.equal(await page.getByTestId("note-changes").textContent(), "1");
      const deniedNotes = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Denied notes", action: "setValue", args: ["Altered"] }] }));
      assert.equal(deniedNotes.ok, false);
      assert.equal(await page.getByRole("textbox", { name: "Denied notes" }).inputValue(), "Private note");
      assert.equal(await page.getByRole("textbox", { name: "Disabled notes" }).isDisabled(), true);
      await notes.evaluate(element => element.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true })));
      assert.equal(await page.getByTestId("note-submits").textContent(), "1");
      assert(snapshot.find(item => item.label === "Agent segment")?.actions.includes("setValue"));
      const segment = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent segment", action: "setValue", args: ["two"] }] }));
      assert.equal(segment.ok, true);
      assert.equal(await page.getByTestId("segment-value").textContent(), "two");
      assert.equal(await page.getByTestId("segment-changes").textContent(), "1");
      const refusedSegment = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Denied segment", action: "setValue", args: ["two"] }] }));
      assert.equal(refusedSegment.ok, false);
      assert.equal(await page.getByTestId("denied-segment-value").textContent(), "one");
      const segmentGroup = page.getByRole("radiogroup", { name: "Agent segment" });
      assert.equal(await segmentGroup.getByRole("radio", { name: "Unavailable" }).isDisabled(), true);
      await segmentGroup.getByRole("radio", { name: "Two" }).focus();
      await page.keyboard.press("ArrowLeft");
      assert.equal(await page.getByTestId("segment-value").textContent(), "one");
      await page.keyboard.press("ArrowLeft");
      assert.equal(await page.getByTestId("segment-value").textContent(), "one");
      assert.equal(await page.getByTestId("segment-changes").textContent(), "2");
      assert(snapshot.find(item => item.label === "Agent tabs")?.actions.includes("setValue"), "installed tabs must be visible to the consumer bridge");
      const changedTab = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent tabs", action: "setValue", args: ["two"] }] }));
      assert.equal(changedTab.ok, true);
      assert.equal(await page.getByTestId("tab-value").textContent(), "two");
      assert.equal(await page.getByTestId("tab-changes").textContent(), "1");
      const refusedTab = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Denied tabs", action: "setValue", args: ["two"] }] }));
      assert.equal(refusedTab.ok, false);
      assert.equal(await page.getByTestId("denied-tab-value").textContent(), "one");
      const tabGroup = page.getByRole("tablist", { name: "Agent tabs" });
      assert.equal(await tabGroup.getByRole("tab", { name: "Unavailable" }).isDisabled(), true);
      const selectedTab = tabGroup.getByRole("tab", { name: "Two" });
      const panelId = await selectedTab.getAttribute("aria-controls");
      assert(panelId);
      assert.equal(await page.locator(`[id="${panelId}"]`).getAttribute("aria-labelledby"), await selectedTab.getAttribute("id"));
      await selectedTab.focus();
      await page.keyboard.press("ArrowRight");
      assert.equal(await page.getByTestId("tab-value").textContent(), "one");
      await page.keyboard.press("End");
      assert.equal(await page.getByTestId("tab-value").textContent(), "two");
      await page.keyboard.press("Home");
      assert.equal(await page.getByTestId("tab-value").textContent(), "one");
      assert.equal(await page.getByTestId("tab-changes").textContent(), "4");
      await tabGroup.getByRole("tab", { name: "One" }).click();
      assert.equal(await page.getByTestId("tab-changes").textContent(), "5");
      const firstPanelId = await tabGroup.getByRole("tab", { name: "One" }).getAttribute("aria-controls");
      const firstPanel = page.locator(`[id="${firstPanelId}"]`);
      await firstPanel.getByRole("textbox", { name: "Panel one" }).fill("Retained");
      await tabGroup.getByRole("tab", { name: "Two" }).click();
      await tabGroup.getByRole("tab", { name: "One" }).click();
      assert.equal(await firstPanel.getByRole("textbox", { name: "Panel one" }).inputValue(), "Retained");
      const unavailable = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Agent tabs", action: "setValue", args: ["disabled"] }] }));
      assert.equal(unavailable.ok, false);
      assert.equal(await page.getByTestId("tab-value").textContent(), "one");
      assert.equal(await page.getByRole("tablist", { name: "Fallback tabs" }).getByRole("tab", { name: "One" }).getAttribute("aria-selected"), "true");
      assert.equal(await page.getByRole("tablist", { name: "Disabled tabs" }).getByRole("tab", { selected: true }).count(), 0);
      const form = page.getByRole("form", { name: "Fixture form" });
      assert.equal(await form.evaluate(element => new FormData(element).get("notes")), "include");
      await form.getByRole("checkbox", { name: "Form checkbox" }).uncheck();
      assert.equal(await form.evaluate(element => new FormData(element).get("notes")), null);
      await form.evaluate(element => element.reset());
      await page.waitForFunction(() => document.querySelector('[name="notes"]')?.checked === true &&
        [...document.querySelectorAll('[role="checkbox"]')].some(node => node.getAttribute("aria-checked") === "true" && node.labels?.[0]?.textContent === "Form checkbox"));
      assert.equal(await form.getByRole("checkbox", { name: "Form checkbox" }).getAttribute("aria-checked"), "true");
      assert.equal(await form.evaluate(element => new FormData(element).get("enabled")), "yes");
      await form.getByRole("switch", { name: "Form switch" }).press("Space");
      assert.equal(await form.evaluate(element => new FormData(element).get("enabled")), null);
      await form.evaluate(element => element.reset());
      await page.waitForFunction(() => document.querySelector('[name="enabled"]')?.checked === true &&
        [...document.querySelectorAll('[role="switch"]')].some(node => node.getAttribute("aria-checked") === "true" && node.labels?.[0]?.textContent === "Form switch"));
      assert.equal(await form.evaluate(element => new FormData(element).get("title")), "Original");
      await form.getByRole("textbox", { name: "Form text" }).fill("Changed");
      assert.equal(await form.evaluate(element => new FormData(element).get("title")), "Changed");
      await form.evaluate(element => element.reset());
      await page.waitForFunction(() => document.querySelector('[name="title"]')?.value === "Original");
      assert.equal(await form.evaluate(element => new FormData(element).get("description")), "Original note");
      await form.getByRole("textbox", { name: "Form notes" }).fill("Changed note");
      assert.equal(await form.evaluate(element => new FormData(element).get("description")), "Changed note");
      await form.evaluate(element => element.reset());
      await page.waitForFunction(() => document.querySelector('[name="description"]')?.value === "Original note");
      const denied = await page.evaluate(() => window.yogurtFixtureAgent.act({ steps: [{ ref: "Denied action", action: "press" }] }));
      assert.equal(denied.ok, false);
      assert.equal(await page.getByTestId("calls").textContent(), "1");
      await button("Focus action").click();
      assert.equal(await button("Agent action").evaluate(element => document.activeElement === element), true);
      await page.keyboard.press("Space");
      assert.equal(await page.getByTestId("calls").textContent(), "2");
      await button("Unavailable action").evaluate(element => element.click());
      await button("Pending action").evaluate(element => element.click());
      assert.equal(await button("Pending action").getAttribute("aria-busy"), "true");
      assert.equal(await button("Disabled action").isDisabled(), true);
      assert.equal(await page.getByTestId("calls").textContent(), "2");
      await button("Ordinary action").click();
      assert.equal(await page.getByTestId("calls").textContent(), "3");
      assert.equal(await page.getByTestId("submits").textContent(), "0");
      await button("Submit form").focus();
      await page.keyboard.press("Enter");
      assert.equal(await page.getByTestId("submits").textContent(), "1");
      assert.deepEqual(errors, []);
      console.log(`Installed controls and agent bridge passed: ${url}`);
      await page.close();
    }
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

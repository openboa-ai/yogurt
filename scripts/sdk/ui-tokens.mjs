import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const brand = read("tokens/brand.json"),
  ui = read("tokens/ui.json");
const find = (obj, path) =>
  path.split(".").reduce((value, key) => value?.[key], obj);
export function dimension(name) {
  const v = ui.geometry[name];
  return typeof v === "number" ? v : find(brand, v);
}
function palette(path) {
  const color = find(brand.color, path);
  if (!color) throw Error("Unknown palette reference " + path);
  return color;
}
const variable = (p) => "var(--boa-color-" + p.replace(".", "-") + ")";
function roleRules(roles) {
  return Object.entries(roles).map(([key, pair]) => {
    pair.forEach(palette);
    return (
      "  --yg-" + key + ": light-dark(" + pair.map(variable).join(", ") + ");"
    );
  });
}
const css = [
  "/* Generated from tokens/brand.json and tokens/ui.json. */",
  ".yg-root {",
  ...roleRules(ui.roles),
];
for (const [k, v] of Object.entries(ui.geometry))
  css.push(
    "  --yg-" +
      k +
      ": " +
      (typeof v === "number"
        ? v + "px"
        : "var(--boa-" + v.replace(".", "-") + ")") +
      ";",
  );
for (const [k, v] of Object.entries(ui.motion))
  css.push("  --yg-" + k + ": " + v + "ms;");
css.push("  --yg-settle: " + ui.easing.settle + ";");
for (const [name, layers] of Object.entries(ui.elevation)) {
  const shadows = layers.map(([y, blur, opacity]) =>
    "0 " + y + "px " + blur + "px color-mix(in srgb, " +
      variable("neutral.1000") + " " + opacity + "%, transparent)"
  );
  css.push("  --yg-" + name + "-shadow: " + shadows.join(", ") + ";");
}
for (const [role, [size, weight]] of Object.entries(ui.types))
  css.push(
    "  --yg-font-" +
      role +
      ": var(--boa-" +
      (weight in brand.type.weight ? "weight" : "role-weight") +
      "-" +
      weight +
      ") " +
      brand.type.size[size] / 16 +
      "rem/" +
      brand.type.lineHeight[size] / 16 +
      "rem var(--boa-font-family);",
  );
css.push("}");
for (const [m, roles] of Object.entries(ui.materials))
  css.push('.yg-root[data-material="' + m + '"] {', ...roleRules(roles), "}");
writeFileSync("styles/ui-tokens.css", css.join("\n") + "\n");
const nativeDir = "packages/native/controls";
mkdirSync(nativeDir, { recursive: true });
function rgb(p) {
  const hex = palette(p);
  return (
    "C.rgb8(" +
    [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(", ") +
    ")"
  );
}
const group = (keys, expression) =>
  keys.map((k) => "    " + k + ": " + expression + ",").join("\n");
const id = (s) => s.replaceAll("-", "_");
const colors = Object.keys(ui.roles);
const rows = [];
for (const [m, over] of Object.entries({ neutral: {}, ...ui.materials })) {
  const roles = { ...ui.roles, ...over };
  rows.push(
    "        ." + m + " => if (dark) .{",
    ...colors.map(
      (k) => "            ." + id(k) + " = " + rgb(roles[k][1]) + ",",
    ),
    "        } else .{",
    ...colors.map(
      (k) => "            ." + id(k) + " = " + rgb(roles[k][0]) + ",",
    ),
    "        },",
  );
}
const zig = [
  "// Generated by scripts/ui-tokens.mjs from the same roles as styles/ui-tokens.css.",
  'const canvas = @import("native_sdk").canvas;',
  "const C = canvas.Color;",
  "pub const Material = enum { neutral, paper, mist };",
  "pub const Roles = struct {",
  group(colors.map(id), "C"),
  "};",
  "pub fn roles(dark: bool, material: Material) Roles {",
  "    return switch (material) {",
  ...rows,
  "    };",
  "}",
  ...Object.keys(ui.geometry).map(
    (k) => "pub const " + id(k) + ": f32 = " + dimension(k) + ";",
  ),
  ...Object.entries(ui.motion).map(
    ([k, v]) => "pub const " + k + "_ms: u32 = " + v + ";",
  ),
  ...Object.entries(ui.types).map(
    ([k, [s]]) => "pub const " + k + "_type: f32 = " + brand.type.size[s] + ";",
  ),
];
writeFileSync(nativeDir + "/tokens.zig", zig.join("\n") + "\n");

const vocabulary = read("content/terms.json").terms.filter((t) =>
  /^(action|state)\./.test(t.id),
);
const words = Object.fromEntries(vocabulary.map((t) => [t.id, t.term]));
mkdirSync("packages/web/src/foundation", { recursive: true });
writeFileSync(
  "packages/web/src/foundation/words.ts",
  "// Generated from content/terms.json.\nexport const words = " +
    JSON.stringify(words, null, 2) +
    " as const;\n",
);
writeFileSync(
  nativeDir + "/words.zig",
  "// Generated from content/terms.json.\n" +
    vocabulary
      .map(
        (t) =>
          "pub const " +
          t.id.replace(/[.-]/g, "_") +
          " = " +
          JSON.stringify(t.term) +
          ";",
      )
      .join("\n") +
    "\n",
);
